/**
 * Derive the assertion counts from a real verification run.
 *
 *   npm run verify > .cache/verify-latest.log   # then
 *   node tools/count-assertions.mjs [log]
 *
 * The total was hand-maintained in two places -- the slide deck and the demo
 * video's captions -- and went stale every time a step was added or a test was
 * written. It was wrong three separate times, once by enough that the parts did
 * not add up to the stated total (103+46+10+10+15+7 = 191, printed as 196). So
 * it comes from the log now: the one number a reader sees is the one the suite
 * actually printed, and adding a check updates it by running one command.
 *
 * The breakdown is per npm script, because that is how the log is structured and
 * because "which step" is the useful granularity when something fails.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const logPath = resolve(root, process.argv[2] ?? '.cache/verify-latest.log');

const log = readFileSync(logPath, 'utf8');

/** Split the log into one section per npm script. */
const sections = [];
let current = null;
for (const line of log.split('\n')) {
  const header = /^> foreign-anomaly@[\d.]+ (\S+)/.exec(line);
  if (header) {
    current = { step: header[1], passes: 0, tests: 0 };
    sections.push(current);
    continue;
  }
  if (!current) continue;
  if (/^PASS /.test(line)) current.passes++;
  const tests = /^\s*Tests\s+(\d+) passed/.exec(line);
  if (tests) current.tests = Number(tests[1]);
  // `search:time` reports "N/M floors leave time to search" instead of PASS
  // lines. Leaving it out would have made the headline total quietly wrong for
  // the same reason the total went wrong three times before.
  const floors = /^(\d+)\/(\d+) floors leave time to search/.exec(line);
  if (floors) current.passes = Number(floors[1]);
}

if (sections.length === 0) {
  throw new Error(`no npm script sections found in ${logPath} -- run npm run verify first`);
}

// Keep only the steps that asserted something, and label them for a reader who
// has not seen the repository.
const LABELS = {
  'copy:check': '文案一致性',
  'voxel:check': '体素碰撞',
  test: '单元测试',
  'assets:check': '资产完整性',
  'splat:check': '高斯泼溅探测',
  'splat:shoot': '真实房间验收',
  'search:time': '可通关性',
  shoot: '程序化房间验收',
  'demo:stills': '演示静帧',
  'deploy:check': '部署检查',
};

const steps = sections
  .map((s) => ({ step: s.step, label: LABELS[s.step] ?? s.step, count: s.passes + s.tests }))
  .filter((s) => s.count > 0);

const total = steps.reduce((sum, s) => sum + s.count, 0);
// The stills step reports "all 9 stills have detail" rather than PASS lines.
const stills = /all (\d+) stills have detail/.exec(log);
const unresolved = [];

const out = {
  total,
  steps,
  note:
    'Generated by tools/count-assertions.mjs from a real npm run verify. ' +
    'Do not edit by hand -- the whole point is that this number cannot drift.',
};
if (stills) out.stills = Number(stills[1]);

// An aborted run must not overwrite a good record with a partial one.
//
// `verify` runs this after every step, but a failure stops it early, and the run
// that stopped at `copy:check` wrote a one-step file over a complete one. The next
// run then compared the docs against a record with no `test` count in it and
// reported "there are undefined unit tests" -- a failure that says nothing about
// the docs. If a step is missing, keep the old file and say so.
// The steps that must all be present for the record to describe a whole suite.
//
// `copy:check` is deliberately not in this list: it *reads* the record, so it runs
// after this file, not inside the chain whose log this parses. Listing it here made
// every honest run look partial -- the record was refused, stayed at its previous
// value, and copy:check then failed against a number no run had produced. A guard
// against stale records became the reason the record was stale.
const EXPECTED = [
  'voxel:check', 'test', 'assets:check', 'splat:check',
  'splat:shoot', 'shoot', 'search:time', 'deploy:check',
];
const missing = EXPECTED.filter((e) => !steps.some((s) => s.step === e));
if (missing.length && !process.argv.includes('--partial')) {
  console.log(
    `\nrefusing to write data/assertions.json: this run has no result for ` +
      `${missing.join(', ')}. The suite stopped early, and a partial record would make ` +
      `the docs look wrong for a reason that has nothing to do with them.`,
  );
  console.log(`(re-run \`npm run verify\`, or pass --partial to record this much)`);
  process.exit(0);
}

writeFileSync(join(root, 'data/assertions.json'), JSON.stringify(out, null, 2) + '\n', 'utf8');

console.log(`${total} assertions across ${steps.length} steps:`);
for (const s of steps) console.log(`  ${String(s.count).padStart(4)}  ${s.label} (${s.step})`);
if (stills) console.log(`  ${String(stills[1]).padStart(4)}  stills with detail (image statistics)`);
if (unresolved.length) console.log(`  unresolved: ${unresolved.join(', ')}`);
console.log('-> data/assertions.json');
